export interface AttributeSchema {
  key: string;
  type: string;
  status: string;
  error: string;
  required: boolean;
  array: boolean;
  default?: any;
  elements?: string[];
  format?: string;
  size?: number;
  min?: number;
  max?: number;
  relatedCollection?: string;
  relationType?: string;
}

export interface CollectionSchema {
  $id: string;
  $createdAt: string;
  $updatedAt: string;
  $permissions: string[];
  databaseId: string;
  name: string;
  enabled: boolean;
  documentSecurity: boolean;
  attributes: AttributeSchema[];
  indexes: any[];
}

export function mapAttributeToTsType(attr: AttributeSchema): string {
  let baseType = "any";

  switch (attr.type) {
    case "string":
      if (attr.format === "enum" && Array.isArray(attr.elements) && attr.elements.length > 0) {
        baseType = attr.elements.map((e) => JSON.stringify(e)).join(" | ");
      } else {
        baseType = "string";
      }
      break;
    case "integer":
    case "float":
    case "double":
      baseType = "number";
      break;
    case "boolean":
      baseType = "boolean";
      break;
    case "datetime":
      baseType = "string"; // ISO Date string
      break;
    case "email":
    case "ip":
    case "url":
      baseType = "string";
      break;
    case "relationship":
      baseType = attr.relatedCollection
        ? `${toPascalCase(attr.relatedCollection)}Document`
        : "Record<string, any>";
      break;
    default:
      baseType = "any";
  }

  if (attr.array) {
    baseType = `${baseType}[]`;
  }

  return baseType;
}

export function toPascalCase(str: string): string {
  return str
    .replace(/[^a-zA-Z0-9_]/g, " ")
    .split(" ")
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");
}

export function generateTypeScriptForCollections(
  databaseId: string,
  collections: CollectionSchema[]
): string {
  let output = `/**
 * Auto-generated by @repo/react-appwrite CLI (appwrite-react-gen)
 * Database ID: ${databaseId}
 * Generated At: ${new Date().toISOString()}
 */

import type { Models } from "appwrite";

`;

  // Generate an interface for each collection
  for (const coll of collections) {
    const typeName = toPascalCase(coll.name || coll.$id);
    const docTypeName = `${typeName}Document`;

    output += `// ==========================================\n`;
    output += `// Collection: ${coll.name} (${coll.$id})\n`;
    output += `// ==========================================\n`;

    output += `export interface ${typeName} {\n`;
    for (const attr of coll.attributes || []) {
      const fieldType = mapAttributeToTsType(attr);
      const optionalFlag = attr.required ? "" : "?";
      output += `  ${attr.key}${optionalFlag}: ${fieldType};\n`;
    }
    output += `}\n\n`;

    output += `export type ${docTypeName} = ${typeName} & Models.Document;\n\n`;
  }

  // Database Collections Map
  output += `export interface ${toPascalCase(databaseId)}DatabaseCollections {\n`;
  for (const coll of collections) {
    const typeName = toPascalCase(coll.name || coll.$id);
    output += `  "${coll.$id}": ${typeName}Document;\n`;
  }
  output += `}\n`;

  return output;
}
