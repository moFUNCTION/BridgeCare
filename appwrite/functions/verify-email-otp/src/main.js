import { Client, Users, Account } from "node-appwrite";

/**
 * Appwrite Cloud Function: verify-email-otp
 * Validates the 6-digit OTP against:
 * 1. Appwrite's built-in token table (from account.createEmailToken)
 * 2. User preferences fallback (from send-email-otp)
 * And marks users.updateEmailVerification(userId, true).
 */
export default async ({ req, res, log, error }) => {
  try {
    const endpoint =
      process.env.APPWRITE_FUNCTION_API_ENDPOINT ||
      process.env.APPWRITE_ENDPOINT ||
      "https://cloud.appwrite.io/v1";

    const projectId =
      process.env.APPWRITE_FUNCTION_PROJECT_ID ||
      process.env.APPWRITE_PROJECT_ID;

    const apiKey =
      req.headers?.["x-appwrite-key"] ||
      process.env.APPWRITE_API_KEY ||
      process.env.APPWRITE_FUNCTION_KEY;

    // Server client with API Key for administrative tasks
    const adminClient = new Client()
      .setEndpoint(endpoint)
      .setProject(projectId);
    if (apiKey) {
      adminClient.setKey(apiKey);
    }
    const users = new Users(adminClient);

    // 1. Extract user identification and submitted OTP
    const headers = req.headers || {};
    let userId = headers["x-appwrite-user-id"];

    let bodyData = {};
    if (typeof req.body === "string" && req.body.trim()) {
      try {
        bodyData = JSON.parse(req.body);
      } catch (e) {
        bodyData = {};
      }
    } else if (typeof req.body === "object" && req.body !== null) {
      bodyData = req.body;
    }

    userId = userId || bodyData.userId;
    const submittedOtp = String(bodyData.otp || "").trim();

    if (!userId) {
      return res.json(
        { success: false, error: "Unauthorized: Missing user authentication context" },
        401
      );
    }

    // Direct elevation if already validated
    if (bodyData.markVerifiedOnly) {
      await users.updateEmailVerification(userId, true);
      log(`Email marked verified for user ${userId} via markVerifiedOnly`);
      return res.json({
        success: true,
        message: "Email successfully verified!",
        verified: true,
      });
    }

    if (!submittedOtp || submittedOtp.length !== 6) {
      return res.json(
        { success: false, error: "Please enter a valid 6-digit OTP code" },
        400
      );
    }

    // 2. Primary Verification: Validate submitted OTP against Appwrite's built-in Token table
    let verifiedViaAppwriteToken = false;
    try {
      const tokenClient = new Client()
        .setEndpoint(endpoint)
        .setProject(projectId);
      const tokenAccount = new Account(tokenClient);

      const session = await tokenAccount.createSession(userId, submittedOtp);
      if (session && session.$id) {
        verifiedViaAppwriteToken = true;
        log(`Successfully verified token for user ${userId} via Appwrite built-in token`);
        // Clean up this temporary session
        try {
          const cleanupClient = new Client()
            .setEndpoint(endpoint)
            .setProject(projectId)
            .setSession(session.secret);
          const cleanupAccount = new Account(cleanupClient);
          await cleanupAccount.deleteSession("current");
        } catch (cleanErr) {
          // Non-critical cleanup
        }
      }
    } catch (tokenErr) {
      log(`Appwrite built-in token validation attempt: ${tokenErr.message}`);
    }

    if (verifiedViaAppwriteToken) {
      // Mark user email as verified
      await users.updateEmailVerification(userId, true);

      // Clear any legacy OTP in preferences
      try {
        const prefs = (await users.getPrefs(userId)) || {};
        if (prefs.emailOtp) {
          await users.updatePrefs(userId, {
            ...prefs,
            emailOtp: null,
            emailOtpExpires: null,
            otpAttempts: 0,
          });
        }
      } catch {}

      return res.json({
        success: true,
        message: "Email successfully verified! Proceeding to application.",
        verified: true,
      });
    }

    // 3. Fallback Verification: Validate against user preferences (if code was generated by send-email-otp)
    const prefs = (await users.getPrefs(userId)) || {};
    const storedOtp = prefs.emailOtp ? String(prefs.emailOtp).trim() : null;
    const expiresAt = Number(prefs.emailOtpExpires || 0);
    const attempts = Number(prefs.otpAttempts || 0);

    if (storedOtp && Date.now() <= expiresAt) {
      if (attempts >= 5) {
        return res.json(
          { success: false, error: "Too many failed attempts. Please request a new verification code." },
          429
        );
      }

      if (storedOtp === submittedOtp) {
        await users.updateEmailVerification(userId, true);
        await users.updatePrefs(userId, {
          ...prefs,
          emailOtp: null,
          emailOtpExpires: null,
          otpAttempts: 0,
        });

        log(`Email successfully verified for user ${userId} via fallback preference OTP`);
        return res.json({
          success: true,
          message: "Email successfully verified! Proceeding to application.",
          verified: true,
        });
      } else {
        await users.updatePrefs(userId, {
          ...prefs,
          otpAttempts: attempts + 1,
        });
        return res.json(
          { success: false, error: `Invalid code. ${4 - attempts} attempts remaining.` },
          400
        );
      }
    }

    return res.json(
      { success: false, error: "Invalid or expired verification code. Please request a new code." },
      400
    );
  } catch (err) {
    error(`verify-email-otp error: ${err.message}`);
    return res.json({ success: false, error: err.message }, 500);
  }
};
